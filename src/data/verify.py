def _probe(path_str: str) -> tuple[str, str | None, str | None, int, int]:
    """Return (path, md5, error, width, height). md5 is None when unreadable."""
    p = Path(path_str)
    try:
        data = p.read_bytes()
        md5 = hashlib.md5(data).hexdigest()
        with Image.open(p) as im:
            im.verify()
        with Image.open(p) as im:
            w, h = im.size
        return path_str, md5, None, w, h
    except Exception as exc:  # noqa: BLE001 - every failure must be recorded
        return path_str, None, f"{type(exc).__name__}: {exc}", 0, 0


def probe_all(paths_list: list[str], workers: int = 8) -> pd.DataFrame:
    rows = []
    with ProcessPoolExecutor(max_workers=workers) as ex:
        for i, res in enumerate(ex.map(_probe, paths_list, chunksize=64), 1):
            rows.append(res)
            if i % 2000 == 0:
                print(f"  probed {i}/{len(paths_list)}", flush=True)
    return pd.DataFrame(rows, columns=["path", "md5", "error", "width", "height"])


def main() -> int:
    paths.ensure_dirs()
    print("building index ...", flush=True)
    df = build_all()

    findings: list[str] = []
    report: list[str] = []
    add = report.append

    add("# Dataset Verification Report")
    add("")
    add("Generated by `src/data/verify.py`. Every count in "
        "`docs/dataset_class_mapping.md` is re-checked against what is on disk.")
    add("")
    add(f"Total images indexed: **{len(df):,}**")
    add("")

    # ---------------- counts ----------------
    add("## 1. Per-class counts vs documented")
    add("")
    for dom, expected in (
        ("plantdoc", EXPECTED_PLANTDOC),
        ("tomatovillage", EXPECTED_TOMATOVILLAGE),
    ):
        d = df[df.domain == dom]
        actual = d.groupby("folder").size().to_dict()
        add(f"### {dom}")
        add("")
        add("| class | documented | on disk | status |")
        add("|---|---:|---:|---|")
        for cls, exp in sorted(expected.items(), key=lambda kv: -kv[1]):
            got = int(actual.get(cls, 0))
            ok = "match" if got == exp else f"**DISCREPANCY {got - exp:+d}**"
            if got != exp:
                findings.append(
                    f"{dom}/{cls}: documented {exp}, on disk {got} ({got - exp:+d})"
                )
            add(f"| {cls} | {exp} | {got} | {ok} |")
        exp_tot, got_tot = sum(expected.values()), int(sum(actual.values()))
        if exp_tot != got_tot:
            findings.append(
                f"{dom} total: documented {exp_tot}, on disk {got_tot} ({got_tot - exp_tot:+d})"
            )
        status = "match" if exp_tot == got_tot else "**DISCREPANCY**"
        add(f"| **total** | **{exp_tot}** | **{got_tot}** | {status} |")
        add("")

    # ---------------- label subsets ----------------
    add("## 2. Shared label-set sizes")
    add("")
    add("| domain | SHARED_3 | SHARED_8 |")
    add("|---|---:|---:|")
    for dom in ("plantvillage", "plantdoc", "tomatovillage"):
        d = df[df.domain == dom]
        add(f"| {dom} | {len(labelled(d, SHARED_3)):,} | {len(labelled(d, SHARED_8)):,} |")
    add("")

    # ---------------- grouping ----------------
    add("## 3. Grouping - the leakage-relevant unit")
    add("")
    pv3 = labelled(df[df.domain == "plantvillage"], SHARED_3)
    cov = pv3[pv3.group_id.notna()]
    per_leaf = len(cov) / max(cov.group_id.nunique(), 1)
    add(f"**PlantVillage SHARED_3:** {len(pv3):,} images on disk, {len(cov):,} with a "
        f"leafmap entry, **{cov.group_id.nunique()} distinct leaves** "
        f"({per_leaf:.3f} images per leaf).")
    add("")
    add("| class | images | leafmap-covered | leaves | documented leaves |")
    add("|---|---:|---:|---:|---:|")
    for folder in sorted(df[df.domain == "plantvillage"].folder.unique()):
        d = df[(df.domain == "plantvillage") & (df.folder == folder)]
        c = d[d.group_id.notna()]
        exp_leaves = EXPECTED_PV_LEAVES.get(folder)
        got_leaves = int(c.group_id.nunique())
        if exp_leaves is not None and exp_leaves != got_leaves:
            findings.append(
                f"plantvillage/{folder}: documented {exp_leaves} leaves, found {got_leaves}"
            )
        add(f"| {folder} | {len(d)} | {len(c)} | {got_leaves} | "
            f"{exp_leaves if exp_leaves else '-'} |")
    add("")

    tv3 = labelled(df[df.domain == "tomatovillage"], SHARED_3)
    n_photos = int(tv3.group_id.nunique())
    n_unparsed = int((tv3.group_kind == "unparsed").sum())
    add(f"**Tomato-Village SHARED_3:** {len(tv3):,} images from **{n_photos} distinct "
        f"photographs** ({len(tv3) / n_photos:.3f} crops per photograph); "
        f"{n_unparsed} filenames failed the `IMG<date><time>[_n]` pattern.")
    add("")
    add("Per capture day:")
    add("")
    add("| capture date | photographs | images | healthy | early_blight | late_blight |")
    add("|---|---:|---:|---:|---:|---:|")
    for day, g in tv3.groupby("capture_date"):
        counts = g.label.value_counts()
        add(f"| {day} | {g.group_id.nunique()} | {len(g)} | "
            f"{counts.get('healthy', 0)} | {counts.get('early_blight', 0)} | "
            f"{counts.get('late_blight', 0)} |")
    add("")

    # ---------------- integrity ----------------
    add("## 4. Integrity - corrupt files and duplicates")
    add("")
    mapped = df[df.label.notna()]
    print(f"probing {len(mapped):,} mapped images ...", flush=True)
    probes = probe_all(mapped.path.tolist())
    merged = mapped.merge(probes, on="path", how="left")

    corrupt = merged[merged.error.notna()]
    add(f"- Unreadable / corrupt images: **{len(corrupt)}**")
    if len(corrupt):
        findings.append(f"{len(corrupt)} corrupt images")
        for _, r in corrupt.head(20).iterrows():
            add(f"  - `{r.path}` - {r.error}")

    dup_groups = (
        merged[merged.md5.notna()]
        .groupby("md5")
        .agg(n=("path", "size"), labels=("label", "nunique"))
    )
    exact_dups = dup_groups[dup_groups.n > 1]
    cross_label = exact_dups[exact_dups.labels > 1]
    n_dup_files = int(exact_dups.n.sum()) if len(exact_dups) else 0
    add(f"- Byte-identical duplicate groups: **{len(exact_dups)}** covering "
        f"{n_dup_files} files")
    add(f"- Duplicate groups spanning **different labels**: **{len(cross_label)}** "
        "(these would be unlearnable and must be excluded)")
    if len(cross_label):
        findings.append(f"{len(cross_label)} duplicate groups span different labels")
    add("")

    add("| domain | duplicate groups |")
    add("|---|---:|")
    for dom in ("plantvillage", "plantdoc", "tomatovillage"):
        d = merged[(merged.domain == dom) & merged.md5.notna()]
        g = d.groupby("md5").size()
        add(f"| {dom} | {int((g > 1).sum())} |")
    add("")

    add("## 5. Findings")
    add("")
    if findings:
        for f in findings:
            add(f"- {f}")
    else:
        add("- No discrepancies.")
    add("")

    out_md = paths.DOCS_DIR / "dataset_verification.md"
    out_md.write_text("\n".join(report), encoding="utf-8")

    merged.drop(columns=["error"]).to_parquet(paths.DATA_DIR / "index.parquet", index=False)
    (paths.DATA_DIR / "verification_findings.json").write_text(
        json.dumps({"findings": findings, "n_images": int(len(df))}, indent=2),
        encoding="utf-8",
    )

    print(f"\nwrote {out_md}")
    print(f"wrote {paths.DATA_DIR / 'index.parquet'}")
    print(f"\n{len(findings)} findings:")
    for f in findings:
        print("  -", f)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
